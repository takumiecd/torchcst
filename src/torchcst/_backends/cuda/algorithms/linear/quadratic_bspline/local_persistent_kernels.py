"""Bounded H/G grid calling unchanged atom cores in logical CTA order."""

import triton as tr
import triton.language as tl

from . import local_kernels as lk


@tr.jit
def forward(
    Bank,
    Meta,
    Pos,
    Co,
    HalfInv,
    H,
    HP,
    Delta,
    Count,
    A: tl.constexpr,
    B: tl.constexpr,
    PI: tl.constexpr,
    PO: tl.constexpr,
    AB: tl.constexpr,
    BB: tl.constexpr,
    SAVE: tl.constexpr,
    BorderDelta=None,
    BorderPos=None,
    SHARDS: tl.constexpr = 0,
    BLOCKS: tl.constexpr = 0,
    Injection=None,
    ENDPOINTS: tl.constexpr = False,
    SHARD_ORIGIN: tl.constexpr = False,
    PAD: tl.constexpr = 0,
    Order=None,
    LAYOUT: tl.constexpr = "soa",
):
    base = tl.load(Count) + tl.program_id(0) * AB
    for start in range(base, A, tl.num_programs(0) * AB):
        lk.forward(
            Bank,
            Meta,
            Pos,
            Co,
            HalfInv,
            H,
            HP,
            Delta,
            Count,
            A,
            B,
            PI,
            PO,
            AB,
            BB,
            SAVE,
            BorderDelta,
            BorderPos,
            SHARDS,
            BLOCKS,
            Injection,
            ENDPOINTS,
            SHARD_ORIGIN,
            PAD,
            Order,
            LAYOUT,
            Base=start,
        )


@tr.jit
def backward(
    InputBank,
    AdjointBank,
    Meta,
    Pos,
    Co,
    HalfInv,
    H,
    HP,
    Delta,
    DP,
    Count,
    A: tl.constexpr,
    B: tl.constexpr,
    PI: tl.constexpr,
    PO: tl.constexpr,
    AB: tl.constexpr,
    BB: tl.constexpr,
    SAVE: tl.constexpr,
    DX: tl.constexpr,
    VJP: tl.constexpr,
    CONTRACT32: tl.constexpr,
    BorderDelta=None,
    BorderPos=None,
    SHARDS: tl.constexpr = 0,
    BLOCKS: tl.constexpr = 0,
    Injection=None,
    ENDPOINTS: tl.constexpr = False,
    SHARD_ORIGIN: tl.constexpr = False,
    PAD: tl.constexpr = 0,
    ADD_DP: tl.constexpr = False,
    Order=None,
    LAYOUT: tl.constexpr = "soa",
):
    base = tl.load(Count) + tl.program_id(0) * AB
    for start in range(base, A, tl.num_programs(0) * AB):
        lk.backward(
            InputBank,
            AdjointBank,
            Meta,
            Pos,
            Co,
            HalfInv,
            H,
            HP,
            Delta,
            DP,
            Count,
            A,
            B,
            PI,
            PO,
            AB,
            BB,
            SAVE,
            DX,
            VJP,
            CONTRACT32,
            BorderDelta,
            BorderPos,
            SHARDS,
            BLOCKS,
            Injection,
            ENDPOINTS,
            SHARD_ORIGIN,
            PAD,
            ADD_DP,
            Order,
            LAYOUT,
            Base=start,
        )
